"""Generate a self-contained private Kaggle T4 pilot script; never launch it.

The embedded archive contains exactly a wheel, contexts, manifest, and protocol.
Model weights are supplied separately by Kaggle modelDataSources. The generated
script reuses the notebook harness, caps inference at 120 calls, and supervises
its worker for at most three hours. This bundler requires only the stdlib.
"""
from __future__ import annotations

import argparse
import ast
import base64
from collections import defaultdict
import hashlib
import io
import json
from pathlib import Path
import re
import zipfile


def digest(value) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                     separators=(",", ":")).encode()).hexdigest()


def validate_inputs(contexts: list[dict], manifest: dict, protocol: dict) -> None:
    if (protocol.get("schema_version") != 2 or protocol.get("response_contract_version") != "files_citations_v2"
            or manifest.get("schema_version") != 2 or manifest.get("response_contract_version") != "files_citations_v2"
            or any(row.get("response_contract_version") != "files_citations_v2" for row in contexts)):
        raise ValueError("Fresh response-contract v2 pilot inputs are required")
    if manifest.get("stage") != "pilot" or manifest.get("token_method") != "tokenizer":
        raise ValueError("Only exact-tokenizer pilot contexts can be bundled")
    if len(contexts) != 60 or manifest.get("cases") != 10 or manifest.get("contexts") != 60:
        raise ValueError("The pilot must contain exactly ten qualified issues and sixty contexts")
    if manifest.get("selection_uses_gold") is not False:
        raise ValueError("Pilot must explicitly declare gold-independent selection")
    if manifest.get("contexts_sha256") != digest(contexts) or manifest.get("protocol_sha256") != digest(protocol):
        raise ValueError("Context or protocol manifest checksum mismatch")
    if protocol.get("sampling_seeds_primary") != [17, 42] or protocol.get("pilot_issues") != 10:
        raise ValueError("This harness requires the preregistered ten-issue, two-seed pilot")
    if not 0 < protocol.get("max_input_tokens", 0) <= 4000 or not 0 < protocol.get("max_output_tokens", 0) <= 256:
        raise ValueError("Pilot input/output token budgets exceed supported limits")
    if not 0 < protocol.get("timeout_seconds", 0) <= 90:
        raise ValueError("Per-attempt elapsed allowance cannot exceed ninety seconds")
    groups = defaultdict(list)
    forbidden = {"patch", "test_patch", "gold", "gold_files", "reference_files", "FAIL_TO_PASS", "PASS_TO_PASS"}
    for context in contexts:
        if forbidden & set(context):
            raise ValueError("Evaluator-only fields detected in context metadata")
        if context.get("token_method") != "tokenizer" or type(context.get("input_tokens")) is not int:
            raise ValueError("Every prompt needs exact tokenizer accounting")
        if context["input_tokens"] > protocol["max_input_tokens"]:
            raise ValueError("A prompt exceeds the total input budget")
        prompt = context["prompt"]
        if hashlib.sha256(prompt.encode()).hexdigest() != context.get("context_sha256"):
            raise ValueError("Prompt hash mismatch")
        if any(marker in prompt for marker in ("known_false_edge_ids", "test_patch", '"patch":')):
            raise ValueError("Evaluator-only marker detected inside a model prompt")
        source = prompt.split("SOURCE PACK\n", 1)[1].split("END SOURCE PACK\n", 1)[0]
        if hashlib.sha256(source.encode()).hexdigest() != context.get("source_sha256"):
            raise ValueError("Source section hash mismatch")
        groups[context["case_id"]].append(context)
    if len(groups) != 10:
        raise ValueError("Pilot has fewer than ten distinct issues")
    for case_id, arms in groups.items():
        if sorted(row["condition"] for row in arms) != sorted(protocol["conditions"]):
            raise ValueError(f"Missing or duplicate conditions for {case_id}")
        if len({row["source_sha256"] for row in arms}) != 1:
            raise ValueError(f"Source differs between conditions for {case_id}")
        if len({row["repo"] for row in arms}) != 1 or arms[0]["repo"] not in protocol["development_repositories"]:
            raise ValueError(f"Unexpected development repository for {case_id}")
    if set(manifest.get("case_ids", [])) != set(groups):
        raise ValueError("Manifest case selection differs from contexts")


RUNTIME = r'''# Generated by GraphTrust-SWE; private development pilot, not a submission.
from __future__ import annotations
import base64
from datetime import datetime, timezone
import hashlib
import io
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import time
import zipfile

BUNDLE_BASE64 = __BUNDLE_BASE64__
BUNDLE_SHA256 = __BUNDLE_SHA256__
BUNDLE_METADATA = __BUNDLE_METADATA__
HARNESS_CODE = __HARNESS_CODE__
MODEL_DIR_OVERRIDE = __MODEL_DIR_OVERRIDE__
MAX_RUNTIME_SECONDS = __MAX_RUNTIME_SECONDS__


def save(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def extract_bundle(working):
    payload = base64.b64decode(BUNDLE_BASE64, validate=True)
    if hashlib.sha256(payload).hexdigest() != BUNDLE_SHA256:
        raise ValueError("Embedded bundle checksum mismatch")
    root = working / "graphtrust-inputs"
    root.mkdir(exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        names = archive.namelist()
        expected = BUNDLE_METADATA["files"]
        if sorted(names) != sorted(expected) or len(names) != len(set(names)):
            raise ValueError("Unexpected archive content")
        for name in names:
            destination = (root / name).resolve()
            if root.resolve() not in destination.parents:
                raise ValueError("Archive path escapes input directory")
            info = archive.getinfo(name)
            if info.file_size != expected[name]["bytes"]:
                raise ValueError("Archive member size mismatch")
            content = archive.read(name)
            if hashlib.sha256(content).hexdigest() != expected[name]["sha256"]:
                raise ValueError("Archive member checksum mismatch")
            if destination.exists() and destination.read_bytes() != content:
                raise ValueError("Different prior inputs exist; preserve them and use a new run")
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
    save(working / "bundle-manifest-used.json", BUNDLE_METADATA)
    return root


def select_model():
    explicit = MODEL_DIR_OVERRIDE or os.environ.get("GRAPHTRUST_MODEL_DIR")
    if explicit:
        chosen = Path(explicit).resolve()
        if not chosen.is_dir():
            raise ValueError("Explicit attached model directory does not exist")
        return chosen
    candidates = []
    for config in Path("/kaggle/input").rglob("config.json"):
        # The official E2B attachment slug identifies the requested model family.
        label = config.parent.as_posix().lower()
        if "gemma" not in label or "e2b" not in label:
            continue
        if any(config.parent.glob("*.safetensors")) or any(config.parent.glob("pytorch_model*.bin")):
            candidates.append(config.parent.resolve())
    candidates = sorted(set(candidates))
    if len(candidates) != 1:
        raise ValueError("Expected exactly one attached official Gemma 4 E2B checkpoint; set an explicit model directory if ambiguous: " + repr([str(p) for p in candidates]))
    return candidates[0]


def finalize_interrupted(working, reason):
    records = working / "records.jsonl"
    journal = working / "records.jsonl.attempts.jsonl"
    if not journal.exists():
        return 0
    terminal_ids = set()
    if records.exists():
        for line in records.read_text(encoding="utf-8").splitlines():
            if line.strip():
                terminal_ids.add(json.loads(line)["run_id"])
    added = 0
    with records.open("a", encoding="utf-8", newline="\n") as output:
        for line in journal.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            started = json.loads(line)
            if started["run_id"] in terminal_ids:
                continue
            terminal = dict(started, status="interrupted", error=reason,
                            error_kind="supervisor_interruption", latency_seconds=None)
            output.write(json.dumps(terminal, sort_keys=True, ensure_ascii=True, separators=(",", ":"), allow_nan=False) + "\n")
            output.flush()
            os.fsync(output.fileno())
            terminal_ids.add(started["run_id"])
            added += 1
    return added


def main():
    started = time.monotonic()
    working = Path("/kaggle/working")
    if not working.is_dir():
        raise RuntimeError("This generated script runs only inside a selected Kaggle session")
    status = {"started_at": datetime.now(timezone.utc).isoformat(),
              "status": "preflight", "max_calls": 120, "max_runtime_seconds": MAX_RUNTIME_SECONDS}
    save(working / "pilot-runtime-status.json", status)
    child = None
    timed_out = False
    try:
        root = extract_bundle(working)
        if hashlib.sha256(HARNESS_CODE.encode()).hexdigest() != BUNDLE_METADATA["worker_sha256"]:
            raise ValueError("Notebook worker checksum mismatch")
        model = select_model()
        save(working / "model-source.json", {"expected_model_id": "google/gemma-4-E2B-it", "attached_directory": str(model)})
        worker = working / "graphtrust-pilot-worker.py"
        worker.write_text(HARNESS_CODE, encoding="utf-8")
        env = dict(os.environ)
        for key in ("GRAPHTRUST_WHEELHOUSE", "GRAPHTRUST_ENV_LOCK", "GRAPHTRUST_MODEL_MANIFEST"):
            env.pop(key, None)
        wheel = root / BUNDLE_METADATA["wheel_archive_path"]
        env.update(GRAPHTRUST_RUN_REAL="1", GRAPHTRUST_BOOTSTRAP="online",
                   GRAPHTRUST_PACKAGE_WHEEL=str(wheel),
                   GRAPHTRUST_PACKAGE_SHA256=BUNDLE_METADATA["files"][BUNDLE_METADATA["wheel_archive_path"]]["sha256"],
                   GRAPHTRUST_MODEL_DIR=str(model), GRAPHTRUST_CONTEXT_DIR=str(root / "contexts"),
                   GRAPHTRUST_PROTOCOL_JSON=str(root / "protocol.json"), PYTHONUNBUFFERED="1")
        status.update(status="running", bundle_sha256=BUNDLE_SHA256,
                      notebook_sha256=BUNDLE_METADATA["notebook_sha256"])
        save(working / "pilot-runtime-status.json", status)
        print("Starting private T4 development pilot: <=120 calls, <=3 hours.", flush=True)
        with (working / "pilot-runtime.log").open("a", encoding="utf-8") as log:
            child = subprocess.Popen([sys.executable, str(worker)], cwd=working, env=env,
                                     stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
            # Reserve ten seconds for termination and final durable diagnostics.
            remaining = max(0, MAX_RUNTIME_SECONDS - (time.monotonic() - started) - 10)
            try:
                child.wait(timeout=remaining)
            except subprocess.TimeoutExpired:
                timed_out = True
                save(working / "BUDGET_STOP.json", {"reason": "Three-hour wall-clock cap reached", "max_runtime_seconds": MAX_RUNTIME_SECONDS})
                # End the full worker group, including a stalled pip child.
                os.killpg(child.pid, signal.SIGTERM)
                try:
                    child.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    os.killpg(child.pid, signal.SIGKILL)
                    child.wait(timeout=5)
        interrupted = finalize_interrupted(working, "Pilot supervisor stopped before an attempt returned")
        diagnostic = working / "pilot-gate-diagnostic.json"
        if not diagnostic.exists():
            save(diagnostic, {"status": "not_frozen", "reason": "Worker did not reach freeze gate", "worker_exit_code": child.returncode, "budget_stopped": timed_out})
        gate = json.loads(diagnostic.read_text())
        status.update(status="budget_stopped" if timed_out else "frozen" if gate.get("status") == "frozen" else "pilot_not_frozen",
                      worker_exit_code=child.returncode, finalized_interrupted_attempts=interrupted,
                      elapsed_seconds=time.monotonic() - started)
        save(working / "pilot-runtime-status.json", status)
        print(json.dumps(status, indent=2), flush=True)
        if child.returncode and not timed_out:
            raise RuntimeError("Pilot worker failed; inspect pilot-runtime.log and preserved diagnostics")
    except Exception as exc:
        if child is not None and child.poll() is None:
            os.killpg(child.pid, signal.SIGKILL)
            child.wait(timeout=5)
            finalize_interrupted(working, "Pilot supervisor failed before an attempt returned")
        status.update(status="error", error=f"{type(exc).__name__}: {exc}", elapsed_seconds=time.monotonic() - started)
        save(working / "pilot-runtime-status.json", status)
        diagnostic = working / "pilot-gate-diagnostic.json"
        if not diagnostic.exists():
            save(diagnostic, {"status": "not_frozen", "error": status["error"]})
        raise


if __name__ == "__main__":
    main()
'''


def build_bundle(wheel: Path, contexts: Path, manifest: Path, protocol: Path,
                 output: Path, notebook: Path, model_dir: str | None = None,
                 max_runtime_seconds: int = 10800) -> dict:
    if not 1 <= max_runtime_seconds <= 10800:
        raise ValueError("Supervisor budget must be between one second and three hours")
    if not re.fullmatch(r"graphtrust_swe-[A-Za-z0-9_.-]+\.whl", wheel.name):
        raise ValueError("Supply a GraphTrust-SWE release wheel")
    rows = [json.loads(line) for line in contexts.read_text(encoding="utf-8").splitlines() if line.strip()]
    metadata = json.loads(manifest.read_text(encoding="utf-8"))
    settings = json.loads(protocol.read_text(encoding="utf-8"))
    validate_inputs(rows, metadata, settings)
    with zipfile.ZipFile(wheel) as package:
        python_files = [{"path": name.removeprefix("graphtrust/"),
                         "sha256": hashlib.sha256(package.read(name)).hexdigest()}
                        for name in sorted(package.namelist())
                        if name.startswith("graphtrust/") and name.endswith(".py")]
    if metadata.get("implementation_sha256") != digest(python_files):
        raise ValueError("Wheel implementation differs from context preparation")
    notebook_bytes = notebook.read_bytes()
    document = json.loads(notebook_bytes)
    code = "\n\n".join("".join(cell["source"]) for cell in document["cells"] if cell["cell_type"] == "code") + "\n"
    compile(code, "graphtrust-pilot-worker.py", "exec")
    required_fragments = ("MAX_CALLS = 120", "TransformersBackend", "backend.count_tokens", "run_contexts", "pilot-gate-diagnostic.json", "freeze")
    if not all(fragment in code for fragment in required_fragments):
        raise ValueError("Notebook harness lacks required inference/accounting gates")
    wheel_name = "package/" + wheel.name
    assets = {wheel_name: wheel.read_bytes(), "contexts/contexts.jsonl": contexts.read_bytes(),
              "contexts/manifest.json": manifest.read_bytes(), "protocol.json": protocol.read_bytes()}
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, content in sorted(assets.items()):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, content)
    archive_bytes = buffer.getvalue()
    bundle_metadata = {
        "schema_version": 1, "purpose": "private_development_pilot_not_competition_submission",
        "files": {name: {"sha256": hashlib.sha256(content).hexdigest(), "bytes": len(content)}
                  for name, content in sorted(assets.items())},
        "wheel_archive_path": wheel_name,
        "notebook_sha256": hashlib.sha256(notebook_bytes).hexdigest(),
        "worker_sha256": hashlib.sha256(code.encode()).hexdigest(),
        "contexts_sha256": metadata["contexts_sha256"], "protocol_sha256": digest(settings),
        "cases": 10, "conditions": 6, "max_calls": 120,
        "max_runtime_seconds": max_runtime_seconds,
        "contains_evaluator_gold": False,
        "model_source": "Official Gemma 4 E2B attachment supplied by Kaggle modelDataSources",
    }
    replacements = {
        "__BUNDLE_BASE64__": repr(base64.b64encode(archive_bytes).decode("ascii")),
        "__BUNDLE_SHA256__": repr(hashlib.sha256(archive_bytes).hexdigest()),
        "__BUNDLE_METADATA__": repr(bundle_metadata), "__HARNESS_CODE__": repr(code),
        "__MODEL_DIR_OVERRIDE__": repr(model_dir), "__MAX_RUNTIME_SECONDS__": str(max_runtime_seconds),
    }
    script = RUNTIME
    for key, value in replacements.items():
        script = script.replace(key, value)
    compile(script, str(output), "exec")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(script, encoding="utf-8", newline="\n")
    result = {**bundle_metadata, "bundle_sha256": hashlib.sha256(archive_bytes).hexdigest(),
              "script_sha256": hashlib.sha256(script.encode()).hexdigest(), "script": str(output),
              "script_bytes": len(script.encode())}
    output.with_suffix(".manifest.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return result


def inspect_script(path: Path) -> dict:
    """Inspect constants and archive without executing the generated script."""
    constants = {}
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in {"BUNDLE_BASE64", "BUNDLE_SHA256", "BUNDLE_METADATA", "HARNESS_CODE", "MAX_RUNTIME_SECONDS"}:
                constants[node.targets[0].id] = ast.literal_eval(node.value)
    archive_bytes = base64.b64decode(constants["BUNDLE_BASE64"], validate=True)
    if hashlib.sha256(archive_bytes).hexdigest() != constants["BUNDLE_SHA256"]:
        raise ValueError("Embedded archive hash mismatch")
    with zipfile.ZipFile(io.BytesIO(archive_bytes)) as archive:
        metadata = constants["BUNDLE_METADATA"]
        if sorted(archive.namelist()) != sorted(metadata["files"]):
            raise ValueError("Archive inventory differs from manifest")
        for name, expected in metadata["files"].items():
            content = archive.read(name)
            if hashlib.sha256(content).hexdigest() != expected["sha256"] or len(content) != expected["bytes"]:
                raise ValueError("Archive file checksum mismatch")
    compile(constants["HARNESS_CODE"], "embedded-notebook-worker", "exec")
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheel", type=Path, required=True)
    parser.add_argument("--contexts", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--protocol", type=Path, default=Path("configs/protocol.json"))
    parser.add_argument("--notebook", type=Path, default=Path(__file__).resolve().parents[1] / "notebooks/kaggle_gemma_pilot.ipynb")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--model-dir", help="Optional actual Kaggle-mounted checkpoint directory; otherwise discover attached E2B")
    parser.add_argument("--max-runtime-seconds", type=int, default=10800)
    args = parser.parse_args()
    result = build_bundle(args.wheel, args.contexts, args.manifest, args.protocol, args.out,
                          args.notebook, args.model_dir, args.max_runtime_seconds)
    inspected = inspect_script(args.out)
    print(json.dumps({"script": result["script"], "script_bytes": result["script_bytes"],
                      "script_sha256": result["script_sha256"], "bundle_sha256": result["bundle_sha256"],
                      "archive_files": sorted(inspected["files"]), "cases": 10, "max_calls": 120,
                      "max_runtime_seconds": result["max_runtime_seconds"], "executed_inference": False}, indent=2))


if __name__ == "__main__":
    main()
